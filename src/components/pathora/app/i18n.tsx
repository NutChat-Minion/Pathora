const merge = (...parts: Defs[]): Defs => {
  const out: Defs = {};
  for (const part of parts) {
    for (const [key, value] of Object.entries(part)) {
      const existing = out[key];
      out[key] =
        Array.isArray(value) || !existing || Array.isArray(existing)
          ? value
          : merge(existing as Defs, value as Defs);
    }
  }
  return out;
};

const defs = merge(d1, d2, d3, d4, d5);

const pick = (node: Defs, index: 0 | 1): Dict => {
  const out: Dict = {};
  for (const [key, value] of Object.entries(node)) {
    out[key] = Array.isArray(value) ? (value as Pair)[index] : pick(value as Defs, index);
  }
  return out;
};

export const en: Dict = pick(defs, 0);
export const th: Dict = pick(defs, 1);
const dictionaries: Record<Lang, Dict> = { en, th };

const lookup = (dict: Dict, key: string): string | undefined => {
  let node: string | Dict | undefined = dict;
  for (const part of key.split(".")) {
    if (!node || typeof node === "string") return undefined;
    node = node[part];
  }
  return typeof node === "string" ? node : undefined;
};

const interpolate = (text: string, vars?: Record<string, string | number>) =>
  vars ? text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match)) : text;

function detectLang(): Lang {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "th") return stored;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("th")
    ? "th"
    : "en";
}

type DateInput = string | number | Date | null | undefined;

type I18nValue = {
  t: TFn;
  lang: Lang;
  setLang: (lang: Lang) => void;
  formatDate: (value: DateInput, options?: Intl.DateTimeFormatOptions) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

/** Must be rendered inside JourneyProvider (it reads and writes the account language). */
export function I18nProvider({ children }: { children: ReactNode }) {
  const { settings, status, updateSettings, setLocale } = useJourney();
  const [localLang, setLocalLang] = useState<Lang>(detectLang);
  const lang: Lang = status === "ready" && settings ? settings.language : localLang;

  useEffect(() => {
    document.documentElement.lang = lang;
    setLocale(lang);
  }, [lang, setLocale]);

  const setLang = useCallback(
    (next: Lang) => {
      setLocalLang(next);
      try {
        window.localStorage.setItem(STORAGE_KEY, next);
      } catch {
        /* storage unavailable */
      }
      if (status === "ready") void updateSettings({ language: next });
    },
    [status, updateSettings],
  );

  const value = useMemo<I18nValue>(() => {
    const locale = lang === "th" ? "th-TH" : "en-GB";
    return {
      lang,
      setLang,
      t: (key, vars) =>
        interpolate(lookup(dictionaries[lang], key) ?? lookup(en, key) ?? key, vars),
      formatDate: (input, options) => {
        if (input === null || input === undefined || input === "") return "";
        const date =
          typeof input === "string" && /^\d{4}-\d{2}-\d{2}$/.test(input)
            ? new Date(`${input}T00:00:00`)
            : new Date(input);
        if (Number.isNaN(date.getTime())) return "";
        return new Intl.DateTimeFormat(
          locale,
          options ?? { day: "numeric", month: "short", year: "numeric" },
        ).format(date);
      },
      formatNumber: (n, options) => new Intl.NumberFormat("en-US", options).format(n),
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useT must be used inside I18nProvider");
  return value;
}

/** EN | ไทย toggle used in the public header and the app navbar. */
export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang, t } = useT();
  const option = (code: Lang, label: string) => (
    <button
      type="button"
      lang={code}
      aria-pressed={lang === code}
      onClick={() => setLang(code)}
      className={`rounded-full px-2.5 py-1 text-[12px] font-bold transition-colors ${
        lang === code ? "bg-[#9d3f68] text-white" : "text-[#716879] hover:text-[#9d3f68]"
      }`}
    >
      {label}
    </button>
  );
  return (
    <div
      role="group"
      aria-label={t("nav.language")}
      className={`inline-flex items-center gap-0.5 rounded-full border border-[#e4d9e6] bg-white p-0.5 ${className}`}
    >
      {option("en", "EN")}
      {option("th", "ไทย")}
    </div>
  );
}
